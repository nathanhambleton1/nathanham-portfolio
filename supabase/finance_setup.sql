-- ---------------------------------------------------------------------------
-- Row Level Security — owner-scoped, authenticated only.
-- `anon` gets nothing: the public anon key alone cannot read a single row.
-- ---------------------------------------------------------------------------

do $$
declare
  t text;
  tables text[] := array[
    'fin_accounts', 'fin_account_balances', 'fin_transaction_categories',
    'fin_transactions', 'fin_transfers', 'fin_paychecks', 'fin_paycheck_deductions',
    'fin_pto_entries', 'fin_subscriptions', 'fin_recurring_expenses', 'fin_sinking_funds',
    'fin_financial_goals', 'fin_retirement_contributions', 'fin_settings',
    'fin_setup_progress', 'fin_monthly_snapshots', 'fin_investment_accounts',
    'fin_securities', 'fin_investment_holdings', 'fin_investment_transactions',
    'fin_security_prices', 'fin_investment_snapshots', 'fin_ai_imports',
    'fin_ai_reviews', 'fin_merchant_rules', 'fin_recurring_suggestions',
    'fin_monthly_ai_insights', 'fin_month_plans', 'fin_paycheck_allocations'
  ];
begin
  foreach t in array tables loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon', t);
    execute format('drop policy if exists %I on public.%I', t || '_owner', t);
    execute format(
      'create policy %I on public.%I for all to authenticated using (owner = auth.uid()) with check (owner = auth.uid())',
      t || '_owner', t
    );
  end loop;
end $$;

-- updated_at triggers for every table that carries the column
do $$
declare
  t text;
begin
  for t in
    select c.table_name
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.column_name = 'updated_at'
      and c.table_name like 'fin\_%'
  loop
    execute format('drop trigger if exists %I on public.%I', t || '_touch', t);
    execute format(
      'create trigger %I before update on public.%I for each row execute function public.fin_touch_updated_at()',
      t || '_touch', t
    );
  end loop;
end $$;


-- ---------------------------------------------------------------------------
-- After a bulk load with explicit ids, move each identity sequence past the
-- highest id present. Without this the next natural insert would collide with
-- a restored row and fail on the primary key.
-- ---------------------------------------------------------------------------

create or replace function public.fin_resync_sequences()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  t text;
  seq text;
  max_id bigint;
begin
  for t in
    select c.table_name
    from information_schema.columns c
    where c.table_schema = 'public'
      and c.column_name = 'id'
      and c.table_name like 'fin\_%'
  loop
    seq := pg_get_serial_sequence('public.' || quote_ident(t), 'id');
    if seq is null then
      continue;
    end if;
    execute format('select coalesce(max(id), 0) from public.%I', t) into max_id;
    perform setval(seq, greatest(max_id, 1), max_id > 0);
  end loop;
end;
$$;

grant execute on function public.fin_resync_sequences() to authenticated;
