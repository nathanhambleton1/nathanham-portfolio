-- =============================================================================
-- NexaFi / Finance — Supabase setup
-- Run once in the Supabase SQL editor (Dashboard → SQL Editor → New query).
--
-- SECURITY NOTE — this is deliberately different from the other tables in this
-- project. travel_*, drunk_*, etc. allow anonymous read/write because they are
-- low-stakes. This is real financial data, so every table here is:
--   * owner-scoped: an `owner` column pinned to auth.uid()
--   * readable/writable ONLY by an authenticated session whose uid matches
--   * closed to the `anon` role entirely
-- The password box on /finance is a Supabase Auth sign-in, not a cosmetic gate.
-- The anon key being public does NOT expose any row below.
--
-- Tables are prefixed `fin_` because this database is shared with the other
-- sub-apps and names like "accounts"/"settings"/"transactions" would collide.
-- =============================================================================

-- Identity columns are `by default` rather than `always` on purpose: the JSON
-- restore and the one-time migration from the old SQLite database both insert
-- explicit ids, because the foreign keys between these tables only stay intact
-- if the original ids are preserved. Sequences are resynced after such a load
-- with public.fin_resync_sequences().

-- ---------------------------------------------------------------------------
-- Helpers
-- ---------------------------------------------------------------------------

create or replace function public.fin_touch_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

